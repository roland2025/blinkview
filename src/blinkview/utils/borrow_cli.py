"""`blink borrow` / `blink return`: the tool side of port borrowing (blinkview/borrow.py).

Imports only blinkview.borrow, so it starts in a fraction of a second - it runs before every
flash.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

PIO_SCRIPT = """\
# blink_borrow.py - PlatformIO extra script: borrows the upload port from a running blink for the
# upload, so blink can keep logging from the same port. Generated by `blink borrow --pio-script`.
#
#   [env:...]
#   extra_scripts = pre:blink_borrow.py
#   upload_port = COM5                    ; the borrow name; needed, a pre-action runs before autodetect
#   upload_flags = --after=no_reset       ; optional, with reset_after_return on the blink source
#
# The source in blink needs allow_borrow: true. BLINK names the blink command if it isn't on PATH.
import os
import subprocess

Import("env")

BLINK = os.environ.get("BLINK", "blink")


def _blink(*args):
    try:
        subprocess.run([BLINK, *args], check=False)
    except FileNotFoundError:
        print(f"blink_borrow: '{BLINK}' not found, uploading without borrowing the port")


def borrow_port(source, target, env):
    port = env.subst("$UPLOAD_PORT")
    if port:
        _blink("borrow", port, "--by", "pio")


def return_port(source, target, env):
    port = env.subst("$UPLOAD_PORT")
    if port:
        _blink("return", port)


env.AddPreAction("upload", borrow_port)
env.AddPostAction("upload", return_port)
"""


def setup_borrow_parser(parser: argparse.ArgumentParser):
    """The `blink borrow` subparser. It only collects the arguments (`args`); run_borrow() parses
    them with parse_borrow_args(), which splits off the command at the first `--` itself -
    argparse before 3.12 mishandles an optional positional followed by `-- command`."""
    _add_borrow_options(parser)
    parser.add_argument("command", nargs=argparse.REMAINDER, help=argparse.SUPPRESS)


def _add_borrow_options(parser: argparse.ArgumentParser):
    parser.description = (
        "Borrow a port from a running blink: the source lending it (allow_borrow) closes the port, and opens it "
        "again when the port is returned. With a command (after --), the port is borrowed while the command runs; "
        "without one, until `blink return NAME` (or until the calling process exits)."
    )
    parser.epilog = (
        "examples:\n"
        "  blink borrow COM5 -- pio run -t upload\n"
        "  blink borrow ttyUSB0 -- idf.py -p /dev/ttyUSB0 flash\n"
        "  blink borrow COM5 && flash.sh && blink return COM5\n"
        "  blink borrow --pio-script > blink_borrow.py"
    )
    parser.formatter_class = argparse.RawDescriptionHelpFormatter
    parser.add_argument(
        "name", nargs="?", help="The borrow name: the port's name (COM5, ttyUSB0) unless the source sets borrow_name"
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=None,
        help="Seconds to wait for blink to close the port (default 3). Then the command runs anyway: "
        "no blink is running, or it doesn't lend this port.",
    )
    parser.add_argument(
        "--strict", action="store_true", help="Fail (exit 1, command not run) when blink did not lend the port in time"
    )
    parser.add_argument(
        "--pid",
        type=int,
        default=None,
        help="The process whose exit ends the borrow (default: the calling process; with a command, this one)",
    )
    parser.add_argument(
        "--by", default=None, help="Who is borrowing, shown in blink's log (default: the command's name)"
    )
    parser.add_argument("--status", action="store_true", help="List the current borrows")
    parser.add_argument(
        "--pio-script", action="store_true", help="Print a PlatformIO extra script that borrows the upload port"
    )


def parse_borrow_args(argv: list) -> argparse.Namespace:
    """`blink borrow`'s own arguments (everything after `borrow`): options and the name before the
    first `--`, the command after it."""
    if "--" in argv:
        split = argv.index("--")
        front, command = argv[:split], argv[split + 1 :]
    else:
        front, command = argv, []
    parser = argparse.ArgumentParser(prog="blink borrow")
    _add_borrow_options(parser)
    parser.add_argument("extra", nargs="*", help=argparse.SUPPRESS)
    args = parser.parse_args(front)
    if args.extra:
        parser.error(f"put the command after --: blink borrow {args.name or 'NAME'} -- {' '.join(args.extra)}")
    args.command = command
    return args


def setup_return_parser(parser: argparse.ArgumentParser):
    parser.description = "Return a port taken with `blink borrow NAME`: blink opens it again within a second."
    parser.add_argument("name", help="The borrow name given to `blink borrow`")


def run_borrow(args) -> None:
    """The `blink borrow` entry point from __main__: re-parses its own part of sys.argv."""
    argv = sys.argv[1:]
    run_borrow_args(parse_borrow_args(argv[argv.index("borrow") + 1 :] if "borrow" in argv else []))


def run_borrow_args(args: argparse.Namespace) -> None:
    from blinkview import borrow

    if args.pio_script:
        sys.stdout.write(PIO_SCRIPT)
        return
    if args.status:
        _print_status(args.name)
        return
    if not args.name:
        print("blink borrow: a borrow name is needed (e.g. COM5)", file=sys.stderr)
        sys.exit(2)

    command = list(args.command)

    try:
        paths = borrow.resolve(args.name)
    except ValueError as e:
        print(f"blink borrow: {e}", file=sys.stderr)
        sys.exit(2)

    pid = args.pid or (os.getpid() if command else borrow.owner_pid())
    by = args.by or (Path(command[0]).stem if command else "")
    timeout = borrow.DEFAULT_WAIT_S if args.timeout is None else args.timeout

    borrow.remove(paths.lent)  # a stale ack would let the tool in before the port is closed
    borrow.write_borrow(paths, pid, by)

    if borrow.wait_for_lent(paths, timeout):
        print(f"blink borrow: {args.name} borrowed", file=sys.stderr)
    elif args.strict:
        borrow.remove(paths.borrow)
        print(f"blink borrow: no blink lent {args.name} within {timeout:g} s ({paths.borrow})", file=sys.stderr)
        sys.exit(1)
    else:
        print(f"blink borrow: no blink is lending {args.name} ({paths.borrow}), continuing", file=sys.stderr)

    if not command:
        return

    try:
        sys.exit(_run(command))
    finally:
        borrow.remove(paths.borrow)


def run_return(args) -> None:
    from blinkview import borrow

    try:
        paths = borrow.resolve(args.name)
    except ValueError as e:
        print(f"blink return: {e}", file=sys.stderr)
        sys.exit(2)
    borrow.remove(paths.borrow)


def _run(command: list) -> int:
    # A list command is not run through a shell, so resolve `pio` -> pio.exe / pio.cmd on Windows
    # the way a shell would.
    executable = shutil.which(command[0]) or command[0]
    try:
        return subprocess.call([executable, *command[1:]])
    except FileNotFoundError:
        print(f"blink borrow: command not found: {command[0]}", file=sys.stderr)
        return 127
    except KeyboardInterrupt:
        return 130


def _print_status(name=None):
    from blinkview import borrow

    if name:
        files = [borrow.resolve(name).borrow]
    else:
        directory = borrow.borrow_dir()
        files = sorted(directory.glob(f"*{borrow.BORROW_SUFFIX}")) if directory.is_dir() else []
        print(f"Borrow directory: {directory}")

    if not files or not any(f.exists() for f in files):
        print("No borrows.")
        return

    for borrow_file in files:
        paths = borrow.BorrowPaths(borrow_file, borrow_file.with_suffix(borrow.LENT_SUFFIX))
        info = borrow.read_borrow(paths)
        if info is None:
            continue
        pid = info.get("pid")
        owner = f"{info.get('by') or 'unknown'} (pid {pid}, {'running' if borrow.pid_alive(pid) else 'gone'})"
        state = "lent" if borrow.is_lent(paths) else "waiting for blink"
        print(f"{borrow_file.stem}: {state}, borrowed by {owner}")
